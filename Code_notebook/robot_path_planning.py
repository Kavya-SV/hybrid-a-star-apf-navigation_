def calculate_total_turn(path):
    """Measures the total change in direction (in degrees) along the path."""
    if len(path) < 3: return 0
    total_angle = 0
    for i in range(1, len(path) - 1):
        v1 = np.array(path[i]) - np.array(path[i-1])
        v2 = np.array(path[i+1]) - np.array(path[i])
        # Calculate angle between segments
        norm_v1 = np.linalg.norm(v1)
        norm_v2 = np.linalg.norm(v2)
        if norm_v1 > 0 and norm_v2 > 0:
            cos_theta = np.clip(np.dot(v1, v2) / (norm_v1 * norm_v2), -1.0, 1.0)
            total_angle += np.degrees(np.arccos(cos_theta))
    return total_angle

def smooth_path(path, weight_data=0.5, weight_smooth=0.1, tolerance=0.00001):
    if not path: return []
    new_path = np.copy(path).astype(float)
    change = tolerance
    while change >= tolerance:
        change = 0.0
        for i in range(1, len(path) - 1):
            for j in range(len(path[i])):
                aux = new_path[i][j]
                new_path[i][j] += weight_data * (path[i][j] - new_path[i][j])
                new_path[i][j] += weight_smooth * (new_path[i-1][j] + new_path[i+1][j] - 2.0 * new_path[i][j])
                change += abs(aux - new_path[i][j])
    return new_path

