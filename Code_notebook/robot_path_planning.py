# --- TECHNIQUE 2 & 3: LOCAL ELASTICITY & C^2 CONTINUITY ---
# Uses Gradient Descent to 'stretch' the path around moving objects
def hybrid_swerve_optimizer(path_window, dynamic_v, k_smooth=0.15, k_ref=0.4, k_repel=1.8):
    """
    Combines Elastic Bands (TVEB) and Potential Fields (APF)
    Goal: Maintain Kinetic Momentum while ensuring Kinematic Smoothness.
    """
    refined = np.array(path_window, dtype=float)
    # Iterative optimization for high predictability
    for _ in range(40):
        for i in range(1, len(refined) - 1):
            # Smoothness: Ensures C^2 Continuity (Acceleration) so robot doesn't 'jitter'
            f_smooth = (refined[i-1] + refined[i+1]) / 2 - refined[i]

            # Anchor: Fidelity to the original A* plan
            f_anchor = path_window[i] - refined[i]

            # Repulsion (APF): Calculates a 'Swerve Vector' instead of a 'Stop Command'
            f_repel = np.zeros(2)
            for obs_pos in dynamic_v:
                diff = refined[i] - obs_pos
                dist = np.linalg.norm(diff)
                if dist < 18.0: # Detection threshold
                    f_repel += (diff / (dist**4)) * 12.0 # Inverse-fourth power for sharp avoidance

            # Apply the journal-grade mathematical combination
            refined[i] += k_smooth * f_smooth + k_ref * f_anchor + f_repel
    return refined

